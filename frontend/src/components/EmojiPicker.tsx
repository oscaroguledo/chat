export function EmojiPicker({ onSelect, onClose }: EmojiPickerProps) {
  const [activeCategory, setActiveCategory] = useState(0);
  const [search, setSearch] = useState('');
  const filteredEmojis = search ?
  categories.flatMap((c) => c.emojis) :
  categories[activeCategory].emojis;
  return (
    <motion.div
      initial={{
        opacity: 0,
        y: 10,
        scale: 0.95
      }}
      animate={{
        opacity: 1,
        y: 0,
        scale: 1
      }}
      exit={{
        opacity: 0,
        y: 10,
        scale: 0.95
      }}
      className="absolute bottom-full left-0 mb-2 w-80 max-w-[calc(100vw-2rem)] bg-chat-card dark:bg-chat-card border border-chat-border dark:border-chat-border rounded-xl shadow-2xl overflow-hidden z-[60]"
      onClick={(e) => e.stopPropagation()}>
      
      {/* Search */}
      <div className="p-2 border-b border-chat-border dark:border-chat-border">
        <input
          type="text"
          placeholder="Search emojis..."
          value={search}
          onChange={(e) => setSearch(e.target.value)}
          className="w-full px-3 py-1.5 bg-chat-area dark:bg-chat-area rounded-lg outline-none text-sm text-chat-text dark:text-chat-text placeholder-chat-muted" />
        
      </div>

      {/* Category tabs */}
      {!search &&
      <div className="flex border-b border-chat-border dark:border-chat-border px-1 overflow-x-auto">
          {categories.map((cat, idx) =>
        <button
          key={cat.name}
          onClick={() => setActiveCategory(idx)}
          className={`flex-shrink-0 p-2 text-lg transition-colors rounded-t-lg ${activeCategory === idx ? 'bg-chat-area dark:bg-chat-area' : 'hover:bg-chat-area/50 dark:hover:bg-chat-area/50'}`}
          title={cat.name}>
          
              {cat.icon}
            </button>
        )}
        </div>
      }

      {/* Emoji grid */}
      <div className="h-56 overflow-y-auto p-2">
        {!search &&
        <p className="text-xs text-chat-muted dark:text-chat-muted font-medium mb-1 px-1">
            {categories[activeCategory].name}
          </p>
        }
        <div className="grid grid-cols-8 gap-0.5">
          {filteredEmojis.map((emoji, idx) =>
          <button
            key={`${emoji}-${idx}`}
            onClick={() => {
              onSelect(emoji);
            }}
            className="w-9 h-9 flex items-center justify-center text-xl hover:bg-chat-area dark:hover:bg-chat-area rounded-lg transition-colors">
            
              {emoji}
            </button>
          )}
        </div>
        {search && filteredEmojis.length === 0 &&
        <p className="text-sm text-chat-muted dark:text-chat-muted text-center py-8">
            No emojis found
          </p>
        }
      </div>
    </motion.div>);

}